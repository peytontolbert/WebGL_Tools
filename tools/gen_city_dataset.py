#!/usr/bin/env python3
"""
Generate a full viewer-ready city dataset (terrain + roads + buildings + props + trees).

This is intended to make it easy to place everything together:
- roads/buildings/trees/props: generated via the existing `pipelines/run.py proc-city`
- terrain: either generated by proc-city OR overwritten from a Trellis (or other) terrain mesh

Outputs a dataset folder containing:
  heightmap/meta.json + heightmap/heights.u16.bin
  roads.geojson
  buildings.geojson
  trees.geojson
  props.geojson
  manifest_entries.json (suggested entries)

Example:
  python3 tools/gen_city_dataset.py \
    --id my_city \
    --out assets/datasets/generated/my_city \
    --origin-lon -76.30 --origin-lat 36.85 \
    --size-m 2400 \
    --grid 256 \
    --update-manifest

Example (overwrite heightmap from a mesh so Trellis terrain aligns with generated vectors):
  python3 tools/gen_city_dataset.py \
    --id my_city \
    --out assets/datasets/generated/my_city \
    --origin-lon -76.30 --origin-lat 36.85 \
    --size-m 2400 \
    --grid 256 \
    --heightmap-mesh assets/generated/trellis/my_terrain.glb \
    --heightmap-grid 256 \
    --update-manifest
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
PIPELINES_RUN = REPO_ROOT / "pipelines" / "run.py"
MESH_TO_HM = REPO_ROOT / "tools" / "mesh_to_heightmap_u16.py"


class CmdError(RuntimeError):
    pass


def _run(cmd: list[str]) -> None:
    p = subprocess.run(cmd, cwd=str(REPO_ROOT))
    if p.returncode != 0:
        raise CmdError(f"Command failed ({p.returncode}): {' '.join(cmd)}")


def _parse(argv: list[str]) -> argparse.Namespace:
    ap = argparse.ArgumentParser(prog="gen_city_dataset.py")
    ap.add_argument("--id", required=True, help="Dataset id (used for manifest entries).")
    ap.add_argument("--out", required=True, help="Output directory (e.g. assets/datasets/generated/my_city).")

    ap.add_argument("--origin-lon", type=float, default=-76.30)
    ap.add_argument("--origin-lat", type=float, default=36.85)
    ap.add_argument("--size-m", type=float, default=2400.0)
    ap.add_argument("--grid", type=int, default=256, help="Proc-city heightmap grid (still used even if overwritten).")
    ap.add_argument("--max-buildings", type=int, default=12000)
    ap.add_argument("--max-trees", type=int, default=25000)
    ap.add_argument("--max-props", type=int, default=12000)
    ap.add_argument("--tile-buildings", action="store_true")
    ap.add_argument("--tile-chunk-m", type=float, default=512.0)

    ap.add_argument("--update-manifest", action="store_true")
    ap.add_argument("--manifest", default="assets/datasets/manifest.json")

    # Optional: overwrite generated heightmap with one derived from a mesh or from an existing heightmap directory.
    ap.add_argument("--heightmap-mesh", default="", help="Optional: terrain mesh to convert into heightmap-u16.")
    ap.add_argument("--heightmap-grid", type=int, default=256, help="Grid for mesh->heightmap conversion.")
    ap.add_argument("--heightmap-dir", default="", help="Optional: directory containing meta.json + heights.u16.bin to copy into <out>/heightmap/")
    ap.add_argument("--blender", default="", help="Optional: blender executable path for mesh->heightmap conversion.")
    ap.add_argument("--heightmap-args", default="", help="Extra args forwarded to tools/mesh_to_heightmap_u16.py.")
    return ap.parse_args(argv)


def _copy_heightmap_dir(src_dir: Path, dst_dir: Path) -> None:
    meta = src_dir / "meta.json"
    binp = src_dir / "heights.u16.bin"
    if not meta.exists() or not binp.exists():
        raise FileNotFoundError(f"heightmap-dir must contain meta.json + heights.u16.bin: {src_dir}")
    dst_dir.mkdir(parents=True, exist_ok=True)
    shutil.copy2(str(meta), str(dst_dir / "meta.json"))
    shutil.copy2(str(binp), str(dst_dir / "heights.u16.bin"))


def main(argv: list[str]) -> int:
    args = _parse(argv)
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    if not PIPELINES_RUN.exists():
        raise FileNotFoundError(str(PIPELINES_RUN))

    # 1) Generate vectors (and default heightmap) using existing pipeline.
    cmd = [
        "python3",
        str(PIPELINES_RUN),
        "proc-city",
        "--id",
        str(args.id),
        "--out",
        str(out_dir),
        "--origin-lon",
        str(float(args.origin_lon)),
        "--origin-lat",
        str(float(args.origin_lat)),
        "--size-m",
        str(float(args.size_m)),
        "--grid",
        str(int(args.grid)),
        "--max-buildings",
        str(int(args.max_buildings)),
        "--max-trees",
        str(int(args.max_trees)),
        "--max-props",
        str(int(args.max_props)),
        "--tile-chunk-m",
        str(float(args.tile_chunk_m)),
    ]
    if bool(args.tile_buildings):
        cmd.append("--tile-buildings")
    if bool(args.update_manifest):
        cmd += ["--update-manifest", "--manifest", str(args.manifest)]
    _run(cmd)

    # 2) Optional: overwrite heightmap from mesh (preferred) or from existing heightmap directory.
    hm_dst = out_dir / "heightmap"
    mesh = str(args.heightmap_mesh or "").strip()
    hm_src_dir = str(args.heightmap_dir or "").strip()
    if mesh:
        if not MESH_TO_HM.exists():
            raise FileNotFoundError(str(MESH_TO_HM))
        inp = Path(mesh)
        if not inp.is_absolute():
            inp = (REPO_ROOT / inp).resolve()
        if not inp.exists():
            raise FileNotFoundError(str(inp))

        half = float(args.size_m) * 0.5
        # Force horizontal bounds so heightmap lives in the same meter frame as the proc-city vectors.
        bounds = f"{-half},{half},{-half},{half}"

        hm_cmd = [
            "python3",
            str(MESH_TO_HM),
            "--in",
            str(inp),
            "--out",
            str(hm_dst),
            "--grid",
            str(int(max(16, min(4096, int(args.heightmap_grid))))),
            "--bounds",
            bounds,
        ]
        blender = str(args.blender or "").strip()
        if blender:
            hm_cmd += ["--blender", blender]
        extra = str(args.heightmap_args or "").strip()
        if extra:
            # Simple split (space-separated). This is a dev tool; keep minimal.
            hm_cmd += extra.split()
        _run(hm_cmd)
    elif hm_src_dir:
        src = Path(hm_src_dir)
        if not src.is_absolute():
            src = (REPO_ROOT / src).resolve()
        _copy_heightmap_dir(src, hm_dst)

    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main(sys.argv[1:]))
    except KeyboardInterrupt:
        raise
    except Exception as e:
        print(f"ERROR: {e}", file=sys.stderr)
        raise SystemExit(2)

